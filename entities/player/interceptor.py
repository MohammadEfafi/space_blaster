from __future__ import annotations

import math

import pygame

from core import settings as S
from entities.bullet import Bullet, BulletKind
from entities.player.base import Player


class Interceptor(Player):
    """رهگیر سریع — سبک، تیز، تهاجمی."""

    NAME        = "INTERCEPTOR"
    DESCRIPTION = "Fast and fragile. Outspeed them or die trying."
    KIND_KEY    = "interceptor"

    MAX_HP:        int   = 3
    SPEED:         float = 480.0
    RADIUS:        float = 18.0
    INVULN_TIME:   float = 2.0
    SHOOT_CD:      float = 0.07
    BULLET_SPEED:  float = 900.0
    BULLET_DAMAGE: int   = 1
    BULLET_KIND:   BulletKind = BulletKind.LASER

    ACCEL: float = 14.0
    DRAG:  float = 9.5

    PRIMARY_COLOR:   tuple[int, int, int] = (60, 220, 255)
    SECONDARY_COLOR: tuple[int, int, int] = (30, 100, 160)
    ACCENT_COLOR:    tuple[int, int, int] = (255, 240, 100)
    HIGHLIGHT_COLOR: tuple[int, int, int] = (235, 245, 255)
    FLAME_COLOR:     tuple[int, int, int] = (100, 200, 255)



    def get_engine_offsets(self) -> list[tuple[float, float, float]]:
        # موقعیت و مقیاس دو خروجی موتور را نسبت به ابعاد سفینه تعیین می‌کند.
        # Defines the positions and scales of the two engine exhaust points relative to the ship.
        return [
            (-0.45, 0.95, 0.85),
            ( 0.45, 0.95, 0.85),
        ]



    def draw_ship(self, surface: pygame.Surface, cx: int, cy: int) -> None:
        # اندازه‌ی سفینه و رنگ‌های مورد استفاده در اجزای مختلف آن آماده می‌شوند.
        # The ship size and the colors used by its different components are prepared.
        r = int(self.radius)
        primary = self.PRIMARY_COLOR
        secondary = self.SECONDARY_COLOR
        highlight = self.HIGHLIGHT_COLOR
        accent = self.ACCENT_COLOR

        # ---- ۱. سایه‌ی زیر ----
        # سایه‌ای کمی بزرگ‌تر از بدنه در زیر سفینه رسم می‌شود تا عمق بصری ایجاد کند.
        # A shadow slightly larger than the hull is drawn beneath the ship to create visual depth.
        shadow_pts = [
            (cx,                  cy - int(r * 1.25) + 2),
            (cx - int(r * 1.30),  cy + int(r * 0.55) + 2),
            (cx + int(r * 1.30),  cy + int(r * 0.55) + 2),
        ]
        pygame.draw.polygon(surface, (5, 30, 60), shadow_pts)

        # ---- ۲. بال‌های تیز پیکانی ----
        # ابتدا بال چپ تعریف می‌شود و مختصات بال راست با قرینه‌سازی آن به دست می‌آید.
        # The left wing is defined first, and the right wing is generated by mirroring its coordinates.
        left_wing = [
            (cx - int(r * 0.35), cy - int(r * 0.30)),
            (cx - int(r * 1.30), cy + int(r * 0.15)),
            (cx - int(r * 1.10), cy + int(r * 0.55)),
            (cx - int(r * 0.30), cy + int(r * 0.45)),
        ]
        right_wing = [(cx + (cx - x), y) for (x, y) in left_wing]

        # بال‌ها ابتدا با رنگ ثانویه پر می‌شوند و سپس حاشیه‌ی آن‌ها با رنگ اصلی رسم می‌شود.
        # The wings are first filled with the secondary color, then outlined with the primary color.
        pygame.draw.polygon(surface, secondary, left_wing)
        pygame.draw.polygon(surface, secondary, right_wing)
        pygame.draw.polygon(surface, primary, left_wing, 2)
        pygame.draw.polygon(surface, primary, right_wing, 2)

        # ---- ۳. خط نئونی روی بال‌ها ----
        # با تغییر علامت، خطوط تزئینی به‌صورت متقارن روی هر دو بال رسم می‌شوند.
        # Changing the sign draws the decorative lines symmetrically on both wings.
        for sign in (-1, 1):
            pygame.draw.line(
                surface, primary,
                (cx + sign * int(r * 0.55), cy - int(r * 0.1)),
                (cx + sign * int(r * 1.15), cy + int(r * 0.30)),
                1,
            )

        # ---- ۴. بدنه‌ی اصلی ----
        # نقاط چندضلعی، فرم باریک و نوک‌تیز بدنه‌ی سفینه را از نمای بالا مشخص می‌کنند.
        # The polygon points define the ship's narrow, pointed hull from a top-down view.
        hull = [
            (cx,                  cy - int(r * 1.25)),
            (cx - int(r * 0.35),  cy - int(r * 0.20)),
            (cx - int(r * 0.45),  cy + int(r * 0.55)),
            (cx,                  cy + int(r * 0.75)),
            (cx + int(r * 0.45),  cy + int(r * 0.55)),
            (cx + int(r * 0.35),  cy - int(r * 0.20)),
        ]
        # بدنه ابتدا با رنگ اصلی پر می‌شود و سپس حاشیه‌ی آن با رنگ روشن ترسیم می‌شود.
        # The hull is first filled with the primary color, then outlined with a lighter color.
        pygame.draw.polygon(surface, primary, hull)
        pygame.draw.polygon(surface, highlight, hull, 2)

        # ---- ۵. نوار مرکزی ----
        # چندضلعی باریک وسط بدنه، نوار مرکزی سفینه را تشکیل می‌دهد.
        # The narrow polygon in the middle of the hull forms the ship's central stripe.
        stripe = [
            (cx,                  cy - int(r * 1.15)),
            (cx - int(r * 0.15),  cy - int(r * 0.20)),
            (cx,                  cy + int(r * 0.30)),
            (cx + int(r * 0.15),  cy - int(r * 0.20)),
        ]
        pygame.draw.polygon(surface, highlight, stripe)

        # خط رنگی روی نوار مرکزی، جزئیات آن را برجسته‌تر می‌کند.
        # The colored line emphasizes the central stripe.
        pygame.draw.line(
            surface, accent,
            (cx, cy - int(r * 1.05)),
            (cx, cy + int(r * 0.25)),
            2,
        )

        # ---- ۶. کابین ----
        # موقعیت و شعاع کابین بر اساس اندازه‌ی سفینه محاسبه می‌شود.
        # The cockpit position and radius are calculated relative to the ship's size.
        cab_y = cy - int(r * 0.30)
        cab_r = max(2, int(r * 0.20))

        # دو دایره‌ی روی‌هم، حاشیه‌ی رنگی و سطح روشن کابین را تشکیل می‌دهند.
        # Two overlapping circles form the cockpit's colored rim and bright center.
        pygame.draw.circle(surface, accent, (cx, cab_y), cab_r + 1)
        pygame.draw.circle(surface, (255, 255, 220), (cx, cab_y), cab_r)

        # ---- ۷. خطوط تزئینی ----
        # خطوط متقارن روی بدنه، جزئیات بیشتری به طراحی سفینه اضافه می‌کنند.
        # Symmetrical lines on the hull add further detail to the ship's design.
        for sign in (-1, 1):
            pygame.draw.line(
                surface, secondary,
                (cx + sign * int(r * 0.25), cy - int(r * 0.4)),
                (cx + sign * int(r * 0.30), cy + int(r * 0.5)),
                1,
            )

        # ---- ۸. رأس‌های درخشان ----
        # برای هر دو نوک بال، جلوه‌ی نور نئونی جداگانه ایجاد می‌شود.
        # A separate neon glow effect is created for each wingtip.
        for sign in (-1, 1):
            tip_x = cx + sign * int(r * 1.25)
            tip_y = cy + int(r * 0.20)
            self._draw_tip_glow(surface, tip_x, tip_y, int(r * 0.15))



    def try_shoot(self) -> list:
        """شلیک با pierce — گلوله از ۲ دشمن رد می‌شه."""
        # در صورت فعال بودن زمان انتظار شلیک یا از بین رفتن سفینه، شلیکی انجام نمی‌شود.
        # No shots are fired while the shooting cooldown is active or the ship is destroyed.
        if self.shoot_cd > 0.0 or not self.alive:
            return []

        # زمان انتظار شلیک و جلوه‌های بصری مربوط به شلیک تنظیم می‌شوند.
        # The shooting cooldown and the visual effects associated with firing are updated.
        self.shoot_cd = self.current_shoot_cd
        self.muzzle_flash = 1.0
        self.recoil = 0.6

        bullets = []
        # زاویه‌ی هر شلیک به بردار سرعت و نقطه‌ی شروع گلوله تبدیل می‌شود.
        # Each firing angle is converted into a velocity vector and a bullet spawn offset.
        for angle_deg in self._get_shot_angles():
            a = math.radians(angle_deg)
            vx = math.cos(a) * self.BULLET_SPEED
            vy = math.sin(a) * self.BULLET_SPEED
            ox = math.cos(a) * (self.radius + 6)
            oy = math.sin(a) * (self.radius + 6)

            # گلوله با مشخصات سفینه ساخته می‌شود و قابلیت عبور از دو دشمن را دارد.
            # A bullet is created with the ship's firing properties and can pierce through two enemies.
            b = Bullet(
                self.x + ox, self.y + oy,
                vx, vy,
                friendly=True,
                kind=self.BULLET_KIND,
                damage=self.BULLET_DAMAGE,
                scene=self.scene,
                pierce=2,
            )
            bullets.append(b)

        # پخش صدای شلیک فقط در صورت وجود صحنه انجام می‌شود.
        # The shooting sound is played only when a scene is available.
        if self.scene is not None:
            try:
                self.scene.audio.play("player_shoot")
            except Exception:
                pass

        return bullets



    def _draw_tip_glow(
        self,
        surface: pygame.Surface,
        x: int, y: int,
        size: int,
    ) -> None:
        """نقطه‌ی درخشان روی رأس بال (نئون)."""
        # اندازه‌ی هاله حداقل روی دو پیکسل تنظیم می‌شود تا جلوه‌ی نور قابل مشاهده بماند.
        # The glow size is clamped to at least two pixels to keep the light effect visible.
        size = max(2, size)
        accent = self.ACCENT_COLOR

        # سطحی شفاف برای ساخت هاله ایجاد می‌شود تا پس‌زمینه‌ی اطراف تغییر نکند.
        # A transparent surface is used for the glow so the surrounding background remains unaffected.
        glow = pygame.Surface((size * 4, size * 4), pygame.SRCALPHA)

        # دایره‌های هم‌مرکز با شعاع و شفافیت متغیر، هاله‌ای تدریجی و نرم می‌سازند.
        # Concentric circles with varying radii and transparency create a smooth, gradual glow.
        for rr in range(size * 2, 0, -1):
            a = int(120 * (1 - rr / (size * 2)))
            if a <= 0:
                continue
            pygame.draw.circle(glow, (*accent, a), (size * 2, size * 2), rr)

        # هاله با ترکیب افزایشی روی سطح اصلی قرار می‌گیرد تا جلوه‌ی درخشش ایجاد شود.
        # The glow is additively blended onto the main surface to create a luminous effect.
        surface.blit(
            glow, (x - size * 2, y - size * 2),
            special_flags=pygame.BLEND_RGBA_ADD,
        )

        # نقطه‌ی سفید مرکزی، روشن‌ترین بخش جلوه‌ی نئونی را تشکیل می‌دهد.
        # The central white dot forms the brightest part of the neon effect.
        pygame.draw.circle(surface, (255, 255, 255), (x, y), max(1, size // 2))


__all__ = ["Interceptor"]