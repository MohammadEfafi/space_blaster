"""
entities/enemies/normal.py
==========================

دشمن نوع اول — STINGER DRONE (زنبور نیش‌زن).

طراحی تهاجمی:
    • بدنه‌ی تیز پیکانی رو به پایین
    • بال‌های مثلثی تیز بیرون‌زده
    • چشم قرمز درخشان با هاله (تهدید)
    • دو موتور کناری با شعله‌ی نارنجی
    • خطوط زره‌ای روی بدنه
    • هیچ شباهتی به پاورآپ یا جمع‌آوری‌کردنی نداره

رفتار:
    • سریع‌ترین دشمن
    • یک ضربه و نابود
    • بدون شلیک
"""

from __future__ import annotations

import math
import pygame

from core import settings as S
from entities.enemies.base import Enemy, EnemyKind


class NormalEnemy(Enemy):
    """STINGER DRONE — رهگیر تیز و تهاجمی."""

    KIND = EnemyKind.NORMAL

    HP          = S.EnemyCfg.Normal.HP
    RADIUS      = S.EnemyCfg.Normal.RADIUS
    SPEED       = S.EnemyCfg.Normal.SPEED
    SCORE       = S.EnemyCfg.Normal.SCORE
    DROP_CHANCE = S.EnemyCfg.Normal.DROP_CHANCE
    BODY_COLOR  = S.Palette.ENEMY_NORMAL



    def update_ai(self, dt: float) -> None:
        """حرکت مستقیم به پایین."""
        # موقعیت عمودی دشمن متناسب با سرعت و زمان سپری‌شده به‌روزرسانی می‌شود.
        # The enemy's vertical position is updated according to its speed and elapsed time.
        self.y += self.SPEED * dt



    def draw_body(self, surface: pygame.Surface, alpha: int = 255) -> None:
        # بصری بزرگ‌تر از hitbox
        # اندازه‌ی ظاهری برای طراحی بزرگ‌تر از شعاع برخورد در نظر گرفته می‌شود.
        # The visual size is intentionally larger than the collision radius.
        r = max(8, int(self.radius * 1.3))
        cx, cy = int(self.x), int(self.y)

        # رنگ‌های پایه، سایه و روشنایی از رنگ اصلی بدنه استخراج می‌شوند.
        # Base, shadow, and highlight colors are derived from the main body color.
        base = self.tint(self.BODY_COLOR)
        dark = self._darker(base, 100)
        darker = self._darker(base, 150)
        bright = self._lighter(base, 70)

        # ---- ۱. بال‌های تیز بیرونی ----
        # بال‌ها پیش از بدنه رسم می‌شوند تا در لایه‌ی پشتی قرار بگیرند.
        # The wings are drawn before the hull so they remain in the background layer.
        self._draw_wings(surface, cx, cy, r, dark, bright)

        # ---- ۲. موتورهای کناری با شعله ----
        # شعله‌ها و هاله‌ی نور موتورهای دو طرف بدنه را نمایش می‌دهند.
        # Flames and glow effects represent the two engines on either side of the hull.
        self._draw_engines(surface, cx, cy, r)

        # ---- ۳. بدنه‌ی اصلی پیکانی ----
        # چندضلعی اصلی، فرم باریک و نوک‌تیز دشمن را ایجاد می‌کند.
        # The main polygon creates the enemy's narrow, pointed shape.
        self._draw_hull(surface, cx, cy, r, base, dark, bright)

        # ---- ۴. خطوط زره ----
        # خطوط داخلی برای نمایش پنل‌ها و جزئیات زره استفاده می‌شوند.
        # Internal lines represent armor panels and surface details.
        self._draw_armor_lines(surface, cx, cy, r, darker)

        # ---- ۵. چشم قرمز درخشان ----
        # چشم در مرکز بدنه رسم می‌شود و با هاله‌ی قرمز برجسته می‌شود.
        # The eye is drawn at the center of the hull and emphasized with a red glow.
        self._draw_eye(surface, cx, cy, r)

        # ---- ۶. فید ورود ----
        # افکت محوشدن فقط هنگام ورود تدریجی دشمن اعمال می‌شود.
        # The fade effect is applied only while the enemy is gradually entering.
        if alpha < 250:
            self._apply_fade(surface, cx, cy, r, alpha)



    def _draw_wings(
        self,
        surface: pygame.Surface,
        cx: int, cy: int, r: int,
        dark: tuple[int, int, int],
        bright: tuple[int, int, int],
    ) -> None:
        """بال‌های تیز پیکانی (رو به پایین)."""
        # بال چپ
        # مختصات بال چپ نسبت به مرکز بدنه تعریف شده‌اند تا اندازه و موقعیت آن با شعاع هماهنگ بماند.
        # The left wing coordinates are relative to the hull center, keeping its size and position proportional to the radius.
        left = [
            (cx - int(r * 0.25), cy - int(r * 0.6)),    # بالا-داخلی
            (cx - int(r * 1.1),  cy - int(r * 0.15)),   # نوک بالا-چپ
            (cx - int(r * 0.95), cy + int(r * 0.35)),   # نوک پایین-چپ
            (cx - int(r * 0.2),  cy + int(r * 0.1)),    # پایین-داخلی
        ]
        # بال راست با قرینه‌سازی افقی نقاط بال چپ ساخته می‌شود.
        # The right wing is generated by horizontally mirroring the left wing's points.
        right = [(cx + (cx - x), y) for (x, y) in left]

        # ابتدا سطح تیره‌ی بال‌ها و سپس خطوط روشن حاشیه رسم می‌شوند.
        # The dark wing surfaces are drawn first, followed by their bright outlines.
        pygame.draw.polygon(surface, dark, left)
        pygame.draw.polygon(surface, dark, right)
        pygame.draw.polygon(surface, bright, left, 2)
        pygame.draw.polygon(surface, bright, right, 2)

        # خط تیره‌ی داخلی روی هر بال
        # خطوط داخلی به هر بال جزئیات ساختاری بیشتری می‌دهند.
        # Internal lines add further structural detail to each wing.
        pygame.draw.line(
            surface, dark,
            (cx - int(r * 0.6), cy - int(r * 0.3)),
            (cx - int(r * 0.85), cy + int(r * 0.2)),
            2,
        )
        pygame.draw.line(
            surface, dark,
            (cx + int(r * 0.6), cy - int(r * 0.3)),
            (cx + int(r * 0.85), cy + int(r * 0.2)),
            2,
        )

    def _draw_engines(self, surface: pygame.Surface, cx: int, cy: int, r: int) -> None:
        """دو موتور کناری با شعله‌ی زنده."""
        # تغییر سینوسی طول شعله، حالت سوسوزدن موتور را ایجاد می‌کند.
        # Sinusoidal variation in flame length creates the engine flickering effect.
        flicker = 0.7 + 0.3 * math.sin(self._t * 20 + 1.0)
        for sign in (-1, 1):
            # علامت منفی و مثبت، موتور را در دو سمت مخالف مرکز قرار می‌دهد.
            # Negative and positive signs position the engines on opposite sides of the center.
            ex = cx + sign * int(r * 0.5)
            ey = cy - int(r * 0.75)
            flame_len = int(r * 0.5 * flicker)

            # هاله‌ی نارنجی
            # چند دایره‌ی نیمه‌شفاف با شعاع کاهشی، درخشش نرم اطراف موتور را می‌سازند.
            # Multiple translucent circles with decreasing radii create a soft glow around the engine.
            for rr in range(6, 0, -2):
                a = int(120 * (1 - rr / 6))
                if a <= 0:
                    continue
                glow = pygame.Surface((rr * 4, rr * 4), pygame.SRCALPHA)
                pygame.draw.circle(glow, (255, 150, 40, a), (rr * 2, rr * 2), rr)
                surface.blit(glow, (ex - rr * 2, ey - rr * 2 - 4),
                             special_flags=pygame.BLEND_RGBA_ADD)

            # شعله
            # دو چندضلعی روی هم، شعله‌ی بیرونی و بخش روشن‌تر داخلی آن را تشکیل می‌دهند.
            # Two overlapping polygons form the outer flame and its brighter inner section.
            pygame.draw.polygon(surface, (255, 140, 40), [
                (ex - int(r * 0.15), ey),
                (ex + int(r * 0.15), ey),
                (ex, ey - flame_len),
            ])
            pygame.draw.polygon(surface, (255, 230, 120), [
                (ex - int(r * 0.08), ey),
                (ex + int(r * 0.08), ey),
                (ex, ey - int(flame_len * 0.6)),
            ])

    def _draw_hull(
        self,
        surface: pygame.Surface,
        cx: int, cy: int, r: int,
        base: tuple[int, int, int],
        dark: tuple[int, int, int],
        bright: tuple[int, int, int],
    ) -> None:
        """بدنه‌ی پیکانی رو به پایین (تهاجمی)."""
        # بدنه: شبیه نوک پیکان
        # نقاط چندضلعی، بدنه‌ای متقارن با نوک کشیده در پایین ایجاد می‌کنند.
        # The polygon points create a symmetrical hull with an elongated lower tip.
        hull = [
            (cx,                 cy - int(r * 0.5)),    # بالا (پشت)
            (cx - int(r * 0.35), cy - int(r * 0.15)),   # چپ بالا
            (cx - int(r * 0.2),  cy + int(r * 0.5)),    # چپ پایین
            (cx,                 cy + int(r * 1.0)),    # نوک پایین (حمله)
            (cx + int(r * 0.2),  cy + int(r * 0.5)),    # راست پایین
            (cx + int(r * 0.35), cy - int(r * 0.15)),   # راست بالا
        ]

        # سایه (عمق)
        # انتقال چندضلعی به سمت پایین، سایه‌ای ظریف برای ایجاد عمق می‌سازد.
        # Shifting the polygon downward creates a subtle shadow that adds depth.
        shadow = [(x, y + 2) for (x, y) in hull]
        pygame.draw.polygon(surface, dark, shadow)

        # بدنه
        # سطح اصلی با رنگ پایه پر و با رنگ روشن دورگیری می‌شود.
        # The main surface is filled with the base color and outlined with the highlight color.
        pygame.draw.polygon(surface, base, hull)
        pygame.draw.polygon(surface, bright, hull, 2)

        # پنل روشن بالای بدنه
        # پنل مثلثی بالایی با نسخه‌ی روشن‌تر رنگ بدنه، از سطح اصلی متمایز می‌شود.
        # The upper triangular panel is distinguished from the main surface using a lighter body color.
        top = [
            (cx,                cy - int(r * 0.4)),
            (cx - int(r * 0.2), cy - int(r * 0.1)),
            (cx + int(r * 0.2), cy - int(r * 0.1)),
        ]
        pygame.draw.polygon(surface, self._lighter(base, 30), top)

    def _draw_armor_lines(
        self,
        surface: pygame.Surface,
        cx: int, cy: int, r: int,
        darker: tuple[int, int, int],
    ) -> None:
        """خطوط زره افقی روی بدنه."""
        # سه خط در ارتفاع‌های مختلف رسم می‌شوند و طول آن‌ها با موقعیتشان تغییر می‌کند.
        # Three lines are drawn at different heights, with their lengths varying according to their positions.
        for y_off in (-0.2, 0.1, 0.4):
            y = cy + int(r * y_off)
            w = int(r * 0.28 * (1 - y_off * 0.5))
            pygame.draw.line(
                surface, darker,
                (cx - w, y), (cx + w, y), 1,
            )

    def _draw_eye(self, surface: pygame.Surface, cx: int, cy: int, r: int) -> None:
        """چشم قرمز درخشان (تهدید)."""
        eye_y = cy + int(r * 0.1)
        eye_r = max(3, int(r * 0.18))

        # هاله‌ی قرمز
        # هاله با دایره‌های نیمه‌شفاف و شعاع کاهشی ساخته می‌شود تا نور به‌تدریج محو شود.
        # The glow is built from translucent circles with decreasing radii to make the light fade gradually.
        glow_size = eye_r * 4
        glow = pygame.Surface((glow_size * 2, glow_size * 2), pygame.SRCALPHA)
        for rr in range(glow_size, 0, -2):
            a = int(140 * (1 - rr / glow_size))
            if a <= 0:
                continue
            pygame.draw.circle(glow, (255, 40, 40, a),
                               (glow_size, glow_size), rr)
        surface.blit(glow, (cx - glow_size, eye_y - glow_size),
                     special_flags=pygame.BLEND_RGBA_ADD)

        # خود چشم
        # دایره‌های تو‌در‌تو، سطح قرمز چشم و دو لایه‌ی روشن‌تر آن را تشکیل می‌دهند.
        # Nested circles form the red eye surface and its two brighter inner layers.
        pygame.draw.circle(surface, (255, 40, 40), (cx, eye_y), eye_r)
        pygame.draw.circle(surface, (255, 200, 200), (cx, eye_y), max(1, eye_r // 2))
        pygame.draw.circle(surface, (255, 255, 255), (cx - 1, eye_y - 1), max(1, eye_r // 4))


__all__ = ["NormalEnemy"]